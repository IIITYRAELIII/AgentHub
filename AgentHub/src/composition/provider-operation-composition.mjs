import { codexTurnActivityGroups } from "../application/task-history.mjs";
import {
  appendRunActivity,
  codexItemActivity,
  replaceRunActivityGroups,
  upsertRunReasoningBlock,
} from "../domain/run-activity.mjs";
import { taskRunKey } from "../domain/task-runs.mjs";
import { providerThreadKey } from "../domain/workspace-stream-identity.mjs";
import { ClaudeEventService } from "../providers/claude/claude-event-service.mjs";
import { isContextCompactionItem } from "../providers/codex/context-compaction-tracker.mjs";
import { CodexEventService } from "../providers/codex/codex-event-service.mjs";
import { CodexHubMcpBridgeRecovery } from "../providers/codex/codex-hub-mcp-bridge-recovery.mjs";
import { discoverCodexRollouts } from "../providers/codex/codex-turn-usage.mjs";
import { resolveHubDeveloperInstructions } from "./hub-developer-instructions-composition.mjs";
import {
  completeCodexLiveItem,
  reduceCodexLiveItemEvent,
  startCodexLiveItem,
} from "../providers/codex/codex-live-item-reducer.mjs";
import {
  codexTurnSnapshot,
  describeCodexItem,
  recoveredCodexAnswer,
} from "../providers/codex/codex-task-snapshot-service.mjs";
import { ClaudeCompletionService, CodexCompletionService } from "../providers/provider-completion-services.mjs";
import { ClaudeRecoveryService, CodexRecoveryService } from "../providers/provider-recovery-services.mjs";
import { ClaudeProviderTaskService, CodexProviderTaskService } from "../providers/provider-task-service.mjs";
import { CodexTurnService, ProviderCancellationService } from "../providers/provider-turn-services.mjs";

export function createProviderOperationComposition({
  claudeContextMaintenance = null,
  removeRuntimeFile,
  taskRuns,
  selectionStore,
  workspaceCatalogStore,
  preTurnInstructions,
  hubMcpService,
  mcpAdmissionCoordinator,
  saveState,
  taskProgress,
  taskObserver,
  managedRunLifecycle,
  runRecovery,
  runCoordinator,
  turnTemporaryFiles,
  turnSpeechButtons,
  turnTokenUsage,
  cancelledManagedClaudeTasks,
  taskDiffs,
  isSelectedRun,
  codexTransportRunning,
  startCodexTransport,
  initializeCodex,
  sendRpc,
  nameCreatedThread,
  activeProjectRoot,
  codexSandboxMode,
  codexModel,
  invalidateTaskCatalog,
  restoreCodexTaskSettings,
  updateActiveCodexThreadSettings,
  clearLatestDiff,
  consumeTurnTokenTracker,
  waitForTurnEndCompletion,
  commandTrace = null,
  rememberCodexSeenTurn,
  rememberLastTaskMessage,
  readCodexThread,
  readCodexTurnUsage,
  applyCodexRolloutContext,
  finalizeCodexRunDelivery,
  completedCodexAnswer,
  persistClaudeRunHistory,
  projectClaudeRunToWorkLog,
  finalizeRunDelivery,
  attachClaudeRunAfterRestart,
  readCodexTaskSnapshot,
  isCodex,
  autoApprove,
  restartRequested,
  launchTurn,
  startTyping,
  telegram,
  codexContextMaintenance,
  streamContextMaintenance,
  contextCompactions,
  resolvedExplicitSkillNames,
  taskExternalActivity,
  stopClaudeRunProcess,
  processIsAlive,
  invalidateCodexThreadRead,
  applyCodexThreadSettings,
  trackTurnTokenUsage,
  latestContextUsage,
  setLatestDiff,
  requestApproval,
  formatCommandApproval,
  formatFileApproval,
  formatPermissionsApproval,
  requestMcpElicitation,
  requestUserInput,
  discardContextCompactionRun,
  wakeDeferredInputs,
}) {
  const pendingCreatedThread = ({ provider, streamId }) => {
    if (!streamId) return null;
    const binding = workspaceCatalogStore.activeThread(streamId);
    return binding?.provider === provider && workspaceCatalogStore.threadNaming(binding)?.status === "pending"
      ? binding : null;
  };
  const bindCreatedThread = ({ provider, threadId, streamId, projectRoot }) => streamId
    ? workspaceCatalogStore.bindThread({ provider, threadId, streamId, projectRoot, source: "created" })
    : workspaceCatalogStore.assignUnknownThread({ provider, threadId, projectRoot }, { source: "created" });
  const codexProviderTasks = new CodexProviderTaskService({
    pendingCreatedThread,
    nameCreatedThread,
    transportRunning: codexTransportRunning,
    startTransport: startCodexTransport,
    initialize: initializeCodex,
    sendRpc,
    discoverLocalTasks: discoverCodexRollouts,
    logWarn: (...args) => console.warn(...args),
    selection: selectionStore,
    bindCreatedThread,
    activeProjectRoot,
    sandboxMode: codexSandboxMode,
    model: codexModel,
    invalidateCatalog: invalidateTaskCatalog,
    restoreSettings: restoreCodexTaskSettings,
    updateSettings: updateActiveCodexThreadSettings,
    clearLatestDiff,
    saveState,
  });
  const claudeProviderTasks = new ClaudeProviderTaskService({
    pendingCreatedThread, bindCreatedThread, nameCreatedThread,
    selection: selectionStore,
    activeProjectRoot,
    clearLatestDiff,
    saveState,
  });
  const codexCompletionService = new CodexCompletionService({
    runForTask: (run) => taskRuns.forTask(run),
    consumeTracker: consumeTurnTokenTracker,
    waitForCompletion: waitForTurnEndCompletion,
    readThread: readCodexThread,
    readTurnUsage: readCodexTurnUsage,
    applyRolloutContext: applyCodexRolloutContext,
    finalizeDelivery: finalizeCodexRunDelivery,
    finishProgress: (...args) => taskProgress().finish(...args),
    completedAnswer: completedCodexAnswer,
    rememberSeenTurn: rememberCodexSeenTurn,
    rememberLastMessage: rememberLastTaskMessage,
    temporaryFiles: turnTemporaryFiles,
    removeFile: removeRuntimeFile,
    speechButtons: turnSpeechButtons,
    logError: (...args) => console.error(...args),
  });
  const claudeCompletionService = new ClaudeCompletionService({
    settleCompaction: (run) => claudeContextMaintenance?.settleRun(run),
    completeMaintenanceRun: (run) => managedRunLifecycle.complete(run),
    runForTask: (run) => taskRuns.forTask(run),
    isSelectedRun,
    reindexRun: (run, previous) => taskRuns.reindex(run, previous),
    setSelectedThread: (sessionId, title) => {
      const streamId = selectionStore.streamId;
      selectionStore.setThread(sessionId, { provider: "claude", streamId, title });
      if (streamId && sessionId && !workspaceCatalogStore.thread({ provider: "claude", threadId: sessionId })) {
        void workspaceCatalogStore.bindThread({
          provider: "claude",
          threadId: sessionId,
          streamId,
          projectRoot: selectionStore.activeProjectRoot,
          source: "created",
        }).catch((error) => {
          console.error("Cannot bind Claude Thread:", error.message);
        });
      }
    },
    saveState,
    finishProgress: (...args) => taskProgress().finish(...args),
    persistHistory: persistClaudeRunHistory,
    projectWorkLog: projectClaudeRunToWorkLog,
    finalizeDelivery: finalizeRunDelivery,
    temporaryFiles: turnTemporaryFiles,
    removeFile: removeRuntimeFile,
    logError: (...args) => console.error(...args),
  });
  const claudeRecoveryService = new ClaudeRecoveryService({
    attach: attachClaudeRunAfterRestart,
    finishInterrupted: (...args) => runRecovery().finishInterrupted(...args),
  });
  const codexRecoveryService = new CodexRecoveryService({
    transportRunning: codexTransportRunning,
    readTaskSnapshot: readCodexTaskSnapshot,
    startTransport: startCodexTransport,
    initialize: initializeCodex,
    isCodex,
    finishInterrupted: (...args) => runRecovery().finishInterrupted(...args),
    readThread: readCodexThread,
    autoApprove,
    restartRequested,
    finishProgress: (...args) => taskProgress().finish(...args),
    completeRun: (run) => managedRunLifecycle.complete(run),
    recoveredAnswer: recoveredCodexAnswer,
    setProgressStage: (...args) => taskProgress().setStage(...args),
    launchTurn,
    reindexRun: (run, previous) => taskRuns.reindex(run, previous),
    scheduleObservedRun: (...args) => taskObserver().schedule(...args),
    startTyping,
    saveState,
    telegram,
    consumeTracker: consumeTurnTokenTracker,
    finalizeDelivery: finalizeCodexRunDelivery,
    turnTokenUsage,
  });
  const codexTurnService = new CodexTurnService({
    ensureThreadNamed: (reference) => nameCreatedThread({ ...reference, recovering: true }),
    sendRpc,
    sandboxMode: codexSandboxMode,
    compactionRecycle: () => codexContextMaintenance.recycleInFlight,
    resolvedSkillNames: resolvedExplicitSkillNames,
    reindexRun: (run, previous) => taskRuns.reindex(run, previous),
    saveState,
    startTyping,
    scheduleObservedRun: (...args) => taskObserver().schedule(...args),
    finishProgress: (...args) => taskProgress().finish(...args),
    completeRun: (run) => managedRunLifecycle.complete(run),
    readThread: readCodexThread,
    developerInstructions: ({ provider, threadId, streamId }) => resolveHubDeveloperInstructions({
      provider,
      threadId,
      streamId,
      workspaceCatalogStore,
      preTurnInstructions,
      hubMcpService,
    }),
    speechButtons: turnSpeechButtons,
    temporaryFiles: turnTemporaryFiles,
    removeFile: removeRuntimeFile,
    turnTokenUsage,
    commandTrace,
  });
  const providerCancellationService = new ProviderCancellationService({
    interruptCodex: (run) => codexTurnService.interrupt(run),
    runForTask: (run) => taskRuns.forTask(run),
    completeRun: (run) => managedRunLifecycle.complete(run),
    readCodexSnapshot: readCodexTaskSnapshot,
    finishObserved: (...args) => taskObserver().finish(...args),
    completeManaged: (run, options) => runCoordinator().completeManaged(run, options),
    taskExternalActivity,
    stopClaudeRun: stopClaudeRunProcess,
    processIsAlive,
    claudeCancellationKey: providerThreadKey,
    saveState,
    cancelledClaudeTasks: cancelledManagedClaudeTasks,
    logWarn: (...args) => console.warn(...args),
    logError: (...args) => console.error(...args),
  });
  const codexHubMcpBridgeRecovery = new CodexHubMcpBridgeRecovery({
    reloadMcp: () => sendRpc("config/mcpServer/reload", {}, {
      timeoutMs: 10_000,
      priority: "critical",
    }),
    readOperation: (requestId) => workspaceCatalogStore.mcpOperation(requestId),
    wakeDeferredInputs,
    setStage: (...args) => taskProgress().setStage(...args),
    logger: console,
  });
  const codexEventService = new CodexEventService({
    invalidateThreadRead: invalidateCodexThreadRead,
    forEvent: (reference) => taskRuns.forEvent(reference),
    reindexRun: (run, previous) => taskRuns.reindex(run, previous),
    applyThreadSettings: applyCodexThreadSettings,
    saveState,
    trackTokenUsage: trackTurnTokenUsage,
    mutateCompaction: (threadId, operation) => contextCompactions.mutate(threadId, operation),
    taskKey: taskRunKey,
    isSelectedRun,
    setSelectedDiff: setLatestDiff,
    appendActivity: appendRunActivity,
    noteActivity: (...args) => taskProgress().noteActivity(...args),
    scheduleProgress: (...args) => taskProgress().schedule(...args),
    appendReasoning: (...args) => taskProgress().appendReasoning(...args),
    upsertReasoningBlock: upsertRunReasoningBlock,
    replaceActivityGroups: replaceRunActivityGroups,
    turnActivityGroups: codexTurnActivityGroups,
    isCompactionItem: isContextCompactionItem,
    contextUsage: latestContextUsage,
    beginCompaction: (threadId, details) => contextCompactions.mutate(threadId, () => contextCompactions.begin(threadId, details)),
    getCompaction: (providerTaskId) => contextCompactions.get(providerTaskId),
    recordContextEstimate: ({ operationId, threadId, turnId, accepted }) => commandTrace?.recordBestEffort?.({
      commandId: operationId, stage: "context-estimate-received", transport: "codex-context",
      outcome: accepted ? "succeeded" : "unknown",
      metadata: { threadId, turnId, accepted },
    }),
    completeUnregisteredTurn: (identity) => streamContextMaintenance.completeUnregisteredTurn(identity),
    settleCompactionTurn: (threadId, details) => contextCompactions.mutate(threadId, () => contextCompactions.settleProviderTurn(threadId, details)),
    rememberRawCompactionItem: (...args) => contextCompactions.rememberRawItem(...args),
    beginCompactionCleanup: (threadId, details) => contextCompactions.mutate(threadId, () => codexContextMaintenance.beginCompactionCleanup(threadId, details)),
    setStage: (...args) => taskProgress().setStage(...args),
    describeItem: describeCodexItem,
    itemActivity: codexItemActivity,
    requestApproval,
    formatCommandApproval,
    formatFileApproval,
    formatPermissionsApproval,
    requestMcpElicitation,
    requestUserInput,
    reduceLiveItemEvent: reduceCodexLiveItemEvent,
    startLiveItem: startCodexLiveItem,
    completeLiveItem: completeCodexLiveItem,
    discardContextCompaction: discardContextCompactionRun,
    consumeTracker: consumeTurnTokenTracker,
    finishObserved: (...args) => taskObserver().finish(...args),
    turnSnapshot: codexTurnSnapshot,
    completeManaged: (run, completion) => runCoordinator().completeManaged(run, completion),
    turnTokenUsage,
    speechButtons: turnSpeechButtons,
    temporaryFiles: turnTemporaryFiles,
    removeFile: removeRuntimeFile,
    taskDiffs,
    logWarn: (...args) => console.warn(...args),
    logError: (...args) => console.error(...args),
    observeMcpProgress: (event) => mcpAdmissionCoordinator?.progress(event),
    observeHubMcpBridge: (event) => codexHubMcpBridgeRecovery.observe(event),
  });
  return {
    codexProviderTasks,
    claudeProviderTasks,
    codexCompletionService,
    claudeCompletionService,
    claudeRecoveryService,
    codexRecoveryService,
    codexTurnService,
    providerCancellationService,
    codexHubMcpBridgeRecovery,
    codexEventService,
    scheduleObservedRun: (...args) => taskObserver().schedule(...args),
  };
}
